#!/bin/bash
# Entrypoint of the workstation container (runs as root).
#
# 1. creates the Linux user Guacamole logs in as (RDP + SSH)
# 2. prepares the persistent home directory
# 3. writes a kubeconfig that uses the pod's ServiceAccount
# 4. optionally enables Docker-in-Docker (dockerd)
# 5. hands over to supervisord (sshd, xrdp, dockerd, token sync)
set -euo pipefail

USER_NAME="${WORKSTATION_USER:-developer}"
USER_PASS="${WORKSTATION_PASSWORD:-developer}"
USER_UID="${WORKSTATION_UID:-1000}"
USER_GID="${WORKSTATION_GID:-1000}"
HOME_DIR="/home/${USER_NAME}"
SA_DIR="/var/run/secrets/kubernetes.io/serviceaccount"
KUBE_DIR="${HOME_DIR}/.kube"

log() { echo "[entrypoint] $*"; }

# --- helper mode used by supervisord: keep a user-readable token copy --------
# Projected ServiceAccount tokens rotate (kubelet refreshes the file), so the
# kubeconfig points at a copy that is refreshed every 5 minutes.
if [ "${1:-}" = "sa-token-sync" ]; then
  while true; do
    if [ -r "${SA_DIR}/token" ]; then
      install -m 0600 -o "${USER_UID}" -g "${USER_GID}" "${SA_DIR}/token" "${KUBE_DIR}/token"
    fi
    sleep 300
  done
fi

# --- 1. user ------------------------------------------------------------------
if ! getent group "${USER_GID}" >/dev/null; then
  groupadd -g "${USER_GID}" "${USER_NAME}"
fi
if ! id "${USER_NAME}" >/dev/null 2>&1; then
  useradd -M -d "${HOME_DIR}" -u "${USER_UID}" -g "${USER_GID}" -s /bin/bash "${USER_NAME}"
fi
echo "${USER_NAME}:${USER_PASS}" | chpasswd
if getent group docker >/dev/null; then
  usermod -aG docker "${USER_NAME}"
fi
if [ "${WORKSTATION_SUDO:-true}" = "true" ]; then
  usermod -aG sudo "${USER_NAME}"
  echo "${USER_NAME} ALL=(ALL) NOPASSWD:ALL" > /etc/sudoers.d/90-workstation
  chmod 0440 /etc/sudoers.d/90-workstation
else
  rm -f /etc/sudoers.d/90-workstation
fi

# --- 2. home directory (PVC: empty and root-owned on first boot) -------------
mkdir -p "${HOME_DIR}"
if [ "$(stat -c %u "${HOME_DIR}")" != "${USER_UID}" ]; then
  log "taking ownership of ${HOME_DIR}"
  chown -R "${USER_UID}:${USER_GID}" "${HOME_DIR}"
fi
if [ ! -f "${HOME_DIR}/.bashrc" ]; then
  log "seeding ${HOME_DIR} from /etc/skel"
  cp -a /etc/skel/. "${HOME_DIR}/"
  chown -R "${USER_UID}:${USER_GID}" "${HOME_DIR}"
fi
chmod 0750 "${HOME_DIR}"
# Guacamole SFTP / RDP drive land here; Firefox and XFCE need these too.
install -d -o "${USER_UID}" -g "${USER_GID}" "${HOME_DIR}/Desktop" "${HOME_DIR}/Downloads"

# --- 3. kubeconfig backed by the pod ServiceAccount ---------------------------
if [ -r "${SA_DIR}/token" ] && [ -r "${SA_DIR}/ca.crt" ]; then
  install -d -m 0700 -o "${USER_UID}" -g "${USER_GID}" "${KUBE_DIR}"
  install -m 0600 -o "${USER_UID}" -g "${USER_GID}" "${SA_DIR}/token" "${KUBE_DIR}/token"
  install -m 0644 -o "${USER_UID}" -g "${USER_GID}" "${SA_DIR}/ca.crt" "${KUBE_DIR}/ca.crt"
  if [ ! -f "${KUBE_DIR}/config" ]; then
    cat > "${KUBE_DIR}/config" <<EOF
apiVersion: v1
kind: Config
clusters:
  - name: in-cluster
    cluster:
      server: https://kubernetes.default.svc
      certificate-authority: ${KUBE_DIR}/ca.crt
users:
  - name: serviceaccount
    user:
      tokenFile: ${KUBE_DIR}/token
contexts:
  - name: in-cluster
    context:
      cluster: in-cluster
      user: serviceaccount
      namespace: ${KUBE_NAMESPACE:-default}
current-context: in-cluster
EOF
    chown "${USER_UID}:${USER_GID}" "${KUBE_DIR}/config"
    chmod 0600 "${KUBE_DIR}/config"
  fi
else
  log "no ServiceAccount token mounted; kubectl will need a kubeconfig"
fi

# --- environment for GUI and SSH sessions ------------------------------------
{
  echo "# generated by the workstation entrypoint"
  for v in HTTP_PROXY HTTPS_PROXY NO_PROXY; do
    if [ -n "${!v:-}" ]; then
      echo "export ${v}=\"${!v}\""
      echo "export $(echo "${v}" | tr '[:upper:]' '[:lower:]')=\"${!v}\""
    fi
  done
  echo "export KUBE_NAMESPACE=\"${KUBE_NAMESPACE:-default}\""
  echo "export MINIKUBE_IN_STYLE=false"
} > /etc/profile.d/workstation-env.sh

# --- sshd / xrdp / dbus housekeeping -----------------------------------------
mkdir -p /run/sshd /var/run/xrdp /run/dbus
ssh-keygen -A >/dev/null
rm -f /var/run/xrdp/*.pid /var/run/xrdp/sockdir/* /run/dbus/pid 2>/dev/null || true
# D-Bus (and therefore xfce4-session) refuses to start without a machine id.
dbus-uuidgen --ensure
if [ ! -s /etc/machine-id ]; then
  cp /var/lib/dbus/machine-id /etc/machine-id
fi

# --- 4. Docker-in-Docker ------------------------------------------------------
rm -f /etc/supervisor/conf.d/dockerd.conf
if [ "${ENABLE_DOCKER:-false}" = "true" ]; then
  # cgroup v2: move ourselves into a child group so dockerd can manage the root
  # (same trick as the official docker:dind entrypoint).
  if [ -f /sys/fs/cgroup/cgroup.controllers ]; then
    mkdir -p /sys/fs/cgroup/init
    xargs -rn1 < /sys/fs/cgroup/cgroup.procs > /sys/fs/cgroup/init/cgroup.procs 2>/dev/null || :
    sed -e 's/ / +/g' -e 's/^/+/' < /sys/fs/cgroup/cgroup.controllers \
      > /sys/fs/cgroup/cgroup.subtree_control 2>/dev/null || :
  fi

  cat > /etc/supervisor/conf.d/dockerd.conf <<EOF
[program:dockerd]
command=/usr/bin/dockerd --host=unix:///var/run/docker.sock --data-root=/var/lib/docker ${DOCKERD_EXTRA_ARGS:-}
priority=50
autorestart=true
stdout_logfile=/dev/stdout
stdout_logfile_maxbytes=0
stderr_logfile=/dev/stderr
stderr_logfile_maxbytes=0
EOF
  log "dockerd enabled (data-root /var/lib/docker)"
else
  log "dockerd disabled (ENABLE_DOCKER=${ENABLE_DOCKER:-false})"
fi

log "workstation ready: user=${USER_NAME} uid=${USER_UID} home=${HOME_DIR}"
exec /usr/bin/supervisord -n -c /etc/supervisor/supervisord.conf
